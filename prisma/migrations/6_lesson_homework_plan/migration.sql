-- Фаза 3: планирование уроков — домашнее задание и пометка планируемой работы.
--
--  * homework    — «что задано К этому уроку»: ученик готовится к дате урока;
--                  NULL — задание не записано.
--  * plannedKind — тип запланированной работы ("control" — контрольная);
--                  словарь значений — ключи GRADE_KINDS (src/lib/grades.ts),
--                  NULL — обычный урок. Это план, а не оценка: на средний балл
--                  не влияет и с Grade.kind не связан.
--
-- Оба столбца nullable и без DEFAULT: на PostgreSQL это изменение метаданных,
-- без переписывания таблицы. Новые индексы не нужны — выборки «впереди» идут
-- по таблице школьного масштаба.
--
-- Миграция написана вручную (из среды разработки нет TCP-доступа к базе)
-- и применяется на Vercel скриптом vercel-build через `prisma migrate deploy`.

ALTER TABLE "Lesson" ADD COLUMN "homework" TEXT;
ALTER TABLE "Lesson" ADD COLUMN "plannedKind" TEXT;

-- Страховка: во время деплоя 5_equal_weights старый код мог записать вес 2
-- уже после применения миграции. Все типы работ равнозначны, вес всегда 1.
UPDATE "Grade" SET "weight" = 1 WHERE "weight" <> 1;
